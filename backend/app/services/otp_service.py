# OTP business logic layer handling secure 6-digit generation, hashing,
# 60s cooldown enforcement, 5-min expiration, 5-attempt limits, and verification.

import secrets
import hashlib
import math
from datetime import datetime, timedelta, timezone

from app.config import (
    OTP_EXPIRY_SECONDS,
    OTP_RESEND_COOLDOWN_SECONDS,
    OTP_MAX_ATTEMPTS,
    OTP_DEV_MODE,
)
from app.dao import otp_dao
from app.services import sms_service


IST_OFFSET = timedelta(hours=5, minutes=30)


def normalize_to_utc(ts: datetime | str | None) -> datetime:
    """
    Standardizes any timestamp (UTC, IST, timezone-aware, ISO string, or naive)
    to a timezone-naive UTC datetime for consistent database comparison.
    """
    if ts is None:
        return datetime.now(timezone.utc).replace(tzinfo=None)

    if isinstance(ts, str):
        raw = ts.strip()
        try:
            dt = datetime.fromisoformat(raw)
        except ValueError:
            for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%dT%H:%M:%S"):
                try:
                    dt = datetime.strptime(raw, fmt)
                    break
                except ValueError:
                    pass
            else:
                raise ValueError(f"Unable to parse timestamp: {raw}")
    elif isinstance(ts, datetime):
        dt = ts
    else:
        raise ValueError(f"Unsupported timestamp type: {type(ts)}")

    # 1. Timezone-aware timestamp: convert directly to UTC naive
    if dt.tzinfo is not None:
        return dt.astimezone(timezone.utc).replace(tzinfo=None)

    # 2. Timezone-naive timestamp:
    # Check if this timestamp looks like an IST timestamp generated by a MySQL/system clock
    # without tzinfo (approx 5 to 6 hours ahead of current UTC time).
    now_utc = datetime.now(timezone.utc).replace(tzinfo=None)
    diff = dt - now_utc
    if timedelta(hours=5) <= diff <= timedelta(hours=6):
        return dt - IST_OFFSET

    return dt


def _hash_otp(phone: str, otp_code: str) -> str:
    """Hashes the OTP code combined with phone number for secure storage."""
    salt = "yojsetu_otp_salt_2026"
    raw = f"{phone}:{otp_code}:{salt}"
    return hashlib.sha256(raw.encode('utf-8')).hexdigest()


def format_phone(phone: str) -> str:
    """
    Standardizes phone numbers into E.164 format.
    - 10-digit Indian numbers -> +91XXXXXXXXXX
    - 11-digit numbers starting with 0 (e.g. 09876543210) -> +91XXXXXXXXXX
    - Numbers with country code 91 (e.g. 919876543210 or +919876543210) -> +91XXXXXXXXXX
    - Valid international numbers with '+' (e.g. +14155552671) -> +<digits>
    - International numbers without '+' (e.g. 14155552671) -> +<digits>
    """
    if not phone:
        return ""
    raw = phone.strip()
    digits = ''.join(c for c in raw if c.isdigit())

    # 10-digit Indian mobile number
    if len(digits) == 10:
        return f"+91{digits}"

    # 11-digit starting with 0 (Indian STD/trunk prefix, e.g. 09876543210)
    if len(digits) == 11 and digits.startswith("0"):
        return f"+91{digits[1:]}"

    # 12-digit Indian number starting with 91 (e.g. 919876543210 or +919876543210)
    if len(digits) == 12 and digits.startswith("91"):
        return f"+{digits}"

    # Number was explicitly provided with '+' prefix (international E.164)
    if raw.startswith("+") and len(digits) >= 7:
        return f"+{digits}"

    # If 11-15 digits provided, treat as international E.164
    if 11 <= len(digits) <= 15:
        return f"+{digits}"

    return raw


def generate_and_send_otp(phone: str, purpose: str = "REGISTER") -> dict:
    """
    Generates a fresh 6-digit cryptographically secure OTP, hashes it,
    persists it via DAO, and dispatches via SMS service.
    Enforces a 60-second resend cooldown using standardized UTC timestamps.
    """
    formatted_phone = format_phone(phone)
    now_utc = datetime.now(timezone.utc).replace(tzinfo=None)

    # Check resend cooldown
    latest_record = otp_dao.get_latest_otp(formatted_phone, purpose)
    if latest_record:
        created_at_utc = normalize_to_utc(latest_record["created_at"])
        elapsed_seconds = (now_utc - created_at_utc).total_seconds()
        if 0 <= elapsed_seconds < OTP_RESEND_COOLDOWN_SECONDS:
            remaining = max(1, math.ceil(OTP_RESEND_COOLDOWN_SECONDS - elapsed_seconds))
            raise ValueError(f"Please wait {remaining} seconds before requesting a new OTP.")

    # Generate 6-digit cryptographically secure OTP
    otp_code = str(100000 + secrets.randbelow(900000))
    otp_hash = _hash_otp(formatted_phone, otp_code)
    expires_at = now_utc + timedelta(seconds=OTP_EXPIRY_SECONDS)

    # Persist in DB explicitly in UTC
    otp_dao.insert_otp(
        phone=formatted_phone,
        otp_hash=otp_hash,
        purpose=purpose,
        expires_at=expires_at,
        created_at=now_utc,
    )

    # Dispatch via SMS service (logs to console in dev mode)
    sms_service.send_otp(formatted_phone, otp_code, purpose)

    response = {
        "message": "OTP sent successfully",
        "expires_in": OTP_EXPIRY_SECONDS,
        "cooldown": OTP_RESEND_COOLDOWN_SECONDS,
    }
    if OTP_DEV_MODE:
        response["dev_otp"] = otp_code
    return response


def verify_otp(phone: str, submitted_otp: str, purpose: str = "REGISTER") -> dict:
    """
    Verifies submitted OTP code against stored hash.
    Checks: existence, verification status, attempt limits, expiration (in UTC), and hash match.
    """
    formatted_phone = format_phone(phone)
    record = otp_dao.get_latest_otp(formatted_phone, purpose)

    if record is None:
        raise ValueError("No OTP request found for this phone number. Please request a new code.")

    if record["verified"]:
        raise ValueError("This OTP has already been verified. Please request a new code.")

    if record["attempts"] >= OTP_MAX_ATTEMPTS:
        raise ValueError("Too many failed attempts. Please request a new OTP.")

    now_utc = datetime.now(timezone.utc).replace(tzinfo=None)
    expires_at_utc = normalize_to_utc(record["expires_at"])

    if now_utc > expires_at_utc:
        raise ValueError("This OTP has expired. Request a new code.")

    expected_hash = _hash_otp(formatted_phone, submitted_otp)
    if record["otp_hash"] != expected_hash:
        otp_dao.increment_attempts(record["id"])
        remaining_attempts = OTP_MAX_ATTEMPTS - (record["attempts"] + 1)
        if remaining_attempts <= 0:
            raise ValueError("Too many failed attempts. Please request a new OTP.")
        raise ValueError(f"Incorrect OTP. {remaining_attempts} attempt(s) remaining.")

    # All checks passed — mark as verified
    otp_dao.mark_verified(record["id"])
    return {"verified": True, "message": "OTP verified successfully."}

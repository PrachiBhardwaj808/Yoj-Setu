/**
 * Resolves any language identifier (code, english name, or native name) to a valid supported language object.
 * Returns null if the language is unsupported.
 */
export function resolveLanguage(input) {
  if (!input || typeof input !== 'string') return null;
  const normalized = input.trim().toLowerCase();

  return (
    SUPPORTED_LANGUAGES.find(
      (lang) =>
        lang.code.toLowerCase() === normalized ||
        lang.name.toLowerCase() === normalized ||
        lang.nativeName.toLowerCase() === normalized
    ) || null
  );
}

/**
 * Validates whether an input corresponds to a supported language.
 */
export function isSupportedLanguage(input) {
  return Boolean(resolveLanguage(input));
}

